/** "lat, lng" override, or a city name (accent- and case-insensitive, prefix ok). */
export function resolvePlace(
  input: string | undefined,
  coords?: string,
): { name: string; lat: number; lng: number } | null {
  const c = coords?.match(/^\s*(-?\d+(?:\.\d+)?)\s*[, ]\s*(-?\d+(?:\.\d+)?)\s*$/);
  if (c) {
    const lat = Number(c[1]);
    const lng = Number(c[2]);
    if (Math.abs(lat) <= 90 && Math.abs(lng) <= 180)
      return { name: input?.trim() || `${lat.toFixed(2)}, ${lng.toFixed(2)}`, lat, lng };
  }
  if (!input?.trim()) return null;
  const q = ALIASES[fold(input)] ?? fold(input);
  const exact = CITIES.find((city) => fold(city.name) === q);
  const hit = exact ?? CITIES.find((city) => fold(city.name).startsWith(q));
  return hit ? { name: input.trim(), lat: hit.lat, lng: hit.lng } : null;
}

export function haversineKm(a: { lat: number; lng: number }, b: { lat: number; lng: number }) {
  const R = 6371;
  const toRad = (d: number) => (d * Math.PI) / 180;
  const dLat = toRad(b.lat - a.lat);
  const dLng = toRad(b.lng - a.lng);
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

